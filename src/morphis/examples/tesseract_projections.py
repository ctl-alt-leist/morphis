"""
Tesseract Projections

The unit tesseract of ℝ⁴ turning steadily in the double rotation generated by

    B = e_14 + ½ e_23

two orthogonal planes at rates 1 and ½, while the view glides through the
projective family of maps to three dimensions. With the screen turned by the
rotor of a bivector T, x' = R̃ x R for R = exp(-½ T), and u = x'_4 the dropped
component, every view is

    Π(x) = ((x'_1, x'_2, x'_3) + u s) / (1 - κ u)

with κ the inverse distance of the eye along e_4 and s a shear. Each parameter is
a coordinate on the family, so moving them continuously moves the picture
continuously. The tour visits

    orthographic     κ = 0: the eye at infinity, the two cubes at x_4 = ±½ overlapping
    perspective      κ = 1/3: the eye at distance 3, the far cube inside the near one
    close eye        κ = 3/5: the eye in close, near cells swelling and far ones shrinking
    turned screen    T = ½π e_34: the screen turned so that e_4 is drawn and e_3 is dropped
    oblique          s ≠ 0, κ = 0: a parallel projection, the dropped direction drawn as s
    orthographic     back where it began

holding each view, then blending to the next by moving every parameter along an
eased fraction. The turn ramps up from rest at the start and down to rest at the
end, and runs at a steady rate in between, through every hold and every blend.
While a blend runs, the recording keeps a fading afterimage, so the change of
view leaves a trace. A caption in the corner names the nearest view.

The tesseract's corners all lie within distance 1 of the origin, so with κ ≤ 3/5
the weight 1 - κ u stays at least 2/5 and every corner is drawn at a finite point.

Run: uv run python -m morphis.examples.tesseract_projections
Record: uv run python -m morphis.examples.tesseract_projections figures/tesseract/tesseract-projections.gif
"""

import sys
from contextlib import nullcontext

from numpy import pi, sin

from morphis.elements import Frame, basis_vectors, euclidean_metric
from morphis.transforms import rotor
from morphis.utils.easing import ease_in_out_cubic
from morphis.visuals import RED, Projective, Scene


FRAME_RATE = 30
DURATION_FADE_IN = 1.0
DURATION_HOLD = 1.6
DURATION_BLEND = 2.0
DURATION_RAMP = 1.5

# The steady rate of the turn, in radians per second
TURN_RATE = 0.7
# The afterimage kept at the middle of a blend
TRAIL = 0.6

CAMERA_POSITION = (4.9, -4.2, 3.3)

VIEWS = (
    ("orthographic", Projective()),
    ("perspective", Projective(eye=1 / 3)),
    ("close eye", Projective(eye=3 / 5)),
    ("turned screen", Projective(eye=1 / 3, turn={(3, 4): pi / 2})),
    ("oblique", Projective(shear=(0.45, 0.3, 0.35))),
    ("orthographic", Projective()),
)


def schedule(time: float) -> tuple[Projective, str, float]:
    """The view at a time into the tour, the name of the nearest view, and how far into a blend it is."""
    period = DURATION_HOLD + DURATION_BLEND
    stop = min(int(time // period), len(VIEWS) - 1)
    blending = (time - stop * period - DURATION_HOLD) / DURATION_BLEND
    is_blending = stop < len(VIEWS) - 1 and blending > 0.0
    fraction = min(blending, 1.0) if is_blending else 0.0

    (name, start), (next_name, end) = VIEWS[stop], VIEWS[min(stop + 1, len(VIEWS) - 1)]
    view = start.toward(end, ease_in_out_cubic(fraction)) if is_blending else start
    nearest = next_name if fraction > 0.5 else name

    return view, nearest, fraction


def turn_rate(time: float, duration: float) -> float:
    """The rate of the turn: eased up from rest, steady, then eased down to rest at the end."""
    rising = ease_in_out_cubic(min(time / DURATION_RAMP, 1.0))
    falling = ease_in_out_cubic(min((duration - time) / DURATION_RAMP, 1.0))

    return TURN_RATE * min(rising, falling)


def create_scene(output: str | None = None) -> Scene:
    """
    Create the tesseract projection tour.

    Shown live in a window, or, given an output path (.gif or .mp4), recorded
    off screen to that file. The afterimage is drawn only into a recording.
    """
    g = euclidean_metric(4)
    e1, e2, e3, e4 = basis_vectors(g)
    B = (e1 ^ e4) + 0.5 * (e2 ^ e3)

    # The cell spanned by the four edge vectors from one corner, centered on the origin
    edges = Frame(e1, e2, e3, e4)
    corner = -0.5 * (e1 + e2 + e3 + e4)
    start_edges, start_corner = edges.copy(), corner.copy()

    scene = Scene(frame_rate=FRAME_RATE, window=output is None, projection=VIEWS[0][1])
    scene.add(edges, color=RED, filled=True, origin=corner)
    scene.fade_in(edges, t=0.0, duration=DURATION_FADE_IN)
    scene.caption(VIEWS[0][0])
    scene.camera(position=CAMERA_POSITION, focal_point=(0.0, 0.0, 0.0))

    def turn(angle: float) -> None:
        R = rotor(B, angle)
        edges.data[...] = start_edges.transform(R).data
        corner.data[...] = (R * start_corner * ~R)[1].data

    recording = scene.record(output) if output else nullcontext()
    with recording as clip:
        t = 0.0
        dt = 1.0 / FRAME_RATE
        for _ in range(int(DURATION_FADE_IN * FRAME_RATE)):
            scene.capture(t)
            t += dt

        # The tour, with the turn's angle accumulated from its rate
        duration = len(VIEWS) * DURATION_HOLD + (len(VIEWS) - 1) * DURATION_BLEND
        angle = 0.0
        for n in range(int(duration * FRAME_RATE) + 1):
            time = n * dt
            view, name, fraction = schedule(time)
            scene.set_projection(view)
            scene.caption(name)
            if clip is not None:
                clip.trail = TRAIL * sin(pi * fraction)

            angle += turn_rate(time, duration) * dt
            turn(angle)
            scene.capture(t)
            t += dt

    return scene


if __name__ == "__main__":
    output = sys.argv[1] if len(sys.argv) > 1 else None
    scene = create_scene(output)
    if output:
        print(f"Saved {output}")
    scene.show()
